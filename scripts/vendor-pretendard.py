#!/usr/bin/env python3
"""Vendor unmodified Pretendard 1.3.9 WOFF2 subsets for the four used weights.

Run from the repository root. No font editing or per-page subset generation.
"""
import hashlib
import io
from pathlib import Path
import re
import subprocess
import tarfile
from urllib.request import urlopen

VERSION = '1.3.9'
SHA256 = '0ffc240cee83be02520fb4ac1b2a0a51052b9d13506ade0ba90c591dbbb3bd53'
URL = f'https://registry.npmjs.org/pretendard/-/pretendard-{VERSION}.tgz'
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'public/fonts/pretendard' / VERSION


def main():
    with urlopen(URL, timeout=60) as response:
        payload = response.read()
    if hashlib.sha256(payload).hexdigest() != SHA256:
        raise ValueError('Unexpected Pretendard archive checksum')
    DEST.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(payload)) as archive:
        css = archive.extractfile('package/dist/web/static/pretendard-dynamic-subset.css').read().decode()
        blocks = []
        for block in re.findall(r'@font-face\s*\{[^}]+\}', css):
            if not re.search(r'font-weight: (400|500|600|700);', block):
                continue
            filename = re.search(r'woff2-dynamic-subset/([^)]*)', block)[1]
            source = 'package/dist/web/static/woff2-dynamic-subset/' + filename
            (DEST / filename).write_bytes(archive.extractfile(source).read())
            block = re.sub(r'src: [^;]+;', f"src: url('/fonts/pretendard/{VERSION}/{filename}') format('woff2');", block)
            blocks.append(block)
        (DEST / 'LICENSE.txt').write_bytes(archive.extractfile('package/dist/LICENSE.txt').read())
    header = f'/* Pretendard {VERSION}, SIL OFL 1.1. Generated by scripts/vendor-pretendard.py. */\n'
    (ROOT / 'src/shared/styles/pretendard.css').write_text(header + '\n'.join(blocks) + '\n')
    subprocess.run(
        ['pnpm', 'exec', 'prettier', '--write', 'src/shared/styles/pretendard.css'],
        cwd=ROOT,
        check=True,
    )
    print(f'Vendored {len(blocks)} original WOFF2 subsets; unicode-range and swap preserved.')


if __name__ == '__main__':
    main()
